export const LANGS = { de, fr };

export function tr(lang) {
  return LANGS[lang] || LANGS.de;
}

export function otherLang(lang) {
  return lang === 'fr' ? 'de' : 'fr';
}

// Für Deutsch darf der Benutzer die Standardtexte in den Einstellungen überschreiben;
// für Französisch gibt es (noch) keine eigene Editiermöglichkeit, daher immer der i18n-Text.
export function resolveText(lang, settingsValue, i18nDefault) {
  if (lang === 'de') return settingsValue || i18nDefault;
  return i18nDefault;
}
